import { describe, expect, it } from 'bun:test';
import { parseAppConfig } from '../parse';
import { toDesired } from '../desired';
import { detectAppNeeds } from './detect';
import { scanFile, scanHits } from './files';
import { generateAppConfig, suggestAppName } from './generate';

const ORDERS = detectAppNeeds(
  [
    scanFile(
      'services/orders/package.json',
      JSON.stringify(
        {
          scripts: { start: 'node dist/server.js', worker: 'node dist/worker.js', migrate: 'node dist/migrate.js', 'invoices:nightly': 'node dist/jobs/invoices.js' },
          dependencies: { pg: '^8.12.0', bullmq: '^5.8.0', '@aws-sdk/client-s3': '^3.600.0', 'node-cron': '^3.0.3' },
        },
        null,
        2,
      ),
    ),
    scanFile('services/orders/.env.example', 'DATABASE_URL=postgres://localhost/orders\nREDIS_URL=redis://localhost:6379\nS3_BUCKET=invoices\nS3_ENDPOINT=http://localhost:9000\n'),
    scanFile('services/orders/Dockerfile', 'FROM node:22-alpine AS runtime\nEXPOSE 3000\n'),
    scanHits('services/orders/src/sync.ts', [{ line: 12, text: "cron.schedule('*/10 * * * *', sync)" }]),
  ],
  { dir: 'services/orders' },
).detections;

/** Generate, then prove it with the parser the controller runs on push. */
function roundTrip(...args: Parameters<typeof generateAppConfig>) {
  const out = generateAppConfig(...args);
  const parsed = parseAppConfig(out.yaml);
  expect(parsed.issues.filter((i) => i.severity === 'error')).toEqual([]);
  expect(parsed.config).toBeDefined();
  return { ...out, parsed: parsed.config! };
}

describe('generateAppConfig', () => {
  it('everything ticked → a valid v1 app, every connection a binding', () => {
    const { yaml, parsed } = roundTrip(ORDERS, { app: 'orders', dir: 'services/orders' });
    expect(parsed).toMatchObject({
      version: 1,
      app: 'orders',
      env: {
        DATABASE_URL: '${{ db.url }}',
        REDIS_URL: '${{ queue.url }}',
        S3_BUCKET: '${{ invoices.bucket }}',
        S3_ENDPOINT: '${{ invoices.endpoint }}',
        S3_ACCESS_KEY_ID: '${{ invoices.access_key_id }}',
        S3_SECRET_ACCESS_KEY_FILE: '${{ invoices.secret_access_key_file }}',
      },
      services: {
        web: { build: 'services/orders', port: 3000, release: 'npm run migrate', replicas: 1 },
        worker: { build: 'services/orders', command: 'npm run worker' },
      },
      resources: { db: { type: 'postgres', version: 16 }, queue: { type: 'queue' }, invoices: { type: 'bucket', access: 'internal' } },
      jobs: { invoices: { schedule: '0 2 * * *', service: 'worker', run: 'npm run invoices:nightly' } },
    });
    // No connection strings in git: the .env.example values never reach the file.
    expect(yaml).not.toMatch(/postgres:\/\/|redis:\/\/|localhost:9000/);
    expect(yaml).toContain('replicas: 1 # node-cron runs in-process');
    expect(yaml.startsWith('# Generated by swarmy from services/orders')).toBe(true);
    // And it plans: managed data + both services wired.
    const d = toDesired(parsed);
    expect(d.resources.map((r) => r.name)).toEqual(['db', 'invoices', 'queue']);
    expect(d.services.find((s) => s.name === 'web')?.dependsOn).toEqual(['db', 'invoices', 'queue']);
  });

  it('unticked detections drop their resources, env and jobs; web stays', () => {
    const { parsed } = roundTrip(ORDERS, { app: 'orders', dir: 'services/orders', selected: ['postgres'] });
    expect(Object.keys(parsed.services)).toEqual(['web']);
    expect(Object.keys(parsed.resources ?? {})).toEqual(['db']);
    expect(parsed.env).toEqual({ DATABASE_URL: '${{ db.url }}' });
    expect(parsed.jobs).toBeUndefined();
    expect(parsed.services.web).not.toHaveProperty('replicas');
  });

  it('Build · advanced writes the build object from the schema keys', () => {
    const { parsed } = roundTrip(ORDERS, {
      app: 'orders',
      dir: 'services/orders',
      selected: [],
      build: { dockerfile: 'Dockerfile', target: 'runtime', args: { NODE_ENV: 'production' }, watch: ['services/orders', 'packages/shared'] },
    });
    expect(parsed.services.web!.build).toEqual({
      path: 'services/orders',
      dockerfile: 'Dockerfile',
      target: 'runtime',
      args: { NODE_ENV: 'production' },
      watch: ['services/orders', 'packages/shared'],
    });
  });

  it('a Vercel cron calls its path on the web service; a clock is a one-copy service', () => {
    const r = detectAppNeeds([
      scanFile('vercel.json', '{ "crons": [ { "path": "/api/cron/cleanup", "schedule": "0 3 * * *" } ] }'),
      scanFile('Procfile', 'web: node server.js --port 8080\nclock: node clock.js\n'),
    ]);
    const { parsed } = roundTrip(r.detections, { app: 'shop' });
    expect(parsed.services.clock).toEqual({ build: '.', command: 'node clock.js', replicas: 1 });
    expect(parsed.jobs?.cleanup).toMatchObject({ schedule: '0 3 * * *', service: 'web' });
    expect(String(parsed.jobs?.cleanup?.run)).toContain("fetch('http://localhost:8080/api/cron/cleanup'");
  });

  it('suggests a valid app name from a folder or repo', () => {
    expect(suggestAppName('services/Orders_API')).toBe('orders-api');
    expect(suggestAppName('https://github.com/northwind/platform.git')).toBe('platform');
    expect(suggestAppName('')).toBe('app');
  });
});

import * as React from 'react';
import { DownloadIcon } from 'lucide-react';
import { Button, CopyButton } from '@swarmy/ui';
import { CardSkeleton } from '@/components/states';
import { agoWords } from '@/components/app-tabs/releases/release-label';
import { useDeployedCompose } from './use-config-file';

function download(name: string, text: string): void {
  const url = URL.createObjectURL(new Blob([text], { type: 'application/yaml' }));
  const a = Object.assign(document.createElement('a'), { href: url, download: name });
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1_000);
}

/**
 * compose.yaml · generated — the compose swarmy compiled from swarmy.yaml
 * and deployed (the newest release's compose source). Plain compose: it
 * runs on vanilla Swarm, so you can export it and walk away. Edits in the
 * editor aren't in it until they're pushed and applied.
 */
export function ComposePanel({ stack, dirty }: { stack: string; dirty: boolean }): React.JSX.Element {
  const { release, pending, none } = useDeployedCompose(stack, true);
  if (pending) return <CardSkeleton lines={12} />;
  if (none || !release) {
    return (
      <div className="calm-card text-muted-foreground px-5 py-6 text-[13.5px]">
        Nothing deployed yet. swarmy compiles compose when it applies this file, then it appears here.
      </div>
    );
  }
  const code = `# generated by swarmy from swarmy.yaml · deployed ${agoWords(release.createdAt)} · runs on plain Docker Swarm\n${release.composeSource.trimEnd()}\n`;
  return (
    <div className="flex min-h-0 flex-col gap-2">
      <div className="flex flex-wrap items-center gap-2">
        <p className="text-muted-foreground text-xs">
          {dirty ? 'What swarmy deployed from the saved file. Your edits join it once they’re pushed.' : 'What swarmy deployed from this file.'}
        </p>
        <div className="ml-auto flex items-center gap-1.5">
          <CopyButton value={code} className="size-8" />
          <Button type="button" size="sm" variant="outline" onClick={() => download(`${stack}.compose.yaml`, code)}>
            <DownloadIcon aria-hidden className="size-4" /> Download
          </Button>
        </div>
      </div>
      <pre tabIndex={0} aria-label="compose.yaml, generated" className="calm-code h-[min(68vh,640px)] min-h-[320px] overflow-auto px-4 py-3 whitespace-pre">
        {code}
      </pre>
    </div>
  );
}
